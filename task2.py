def dfs(graph, start):
    visited = set()
    stack = [start]
    path = []

    while stack:
        vertex = stack.pop()
        if vertex not in visited:
            visited.add(vertex)
            path.append(vertex)
            stack.extend(
                neighbor
                for neighbor in graph.neighbors(vertex)
                if neighbor not in visited
            )
    return path


def bfs(graph, start):
    visited = set()
    queue = [start]
    path = []

    while queue:
        vertex = queue.pop(0)
        if vertex not in visited:
            visited.add(vertex)
            path.append(vertex)
            queue.extend(
                neighbor
                for neighbor in graph.neighbors(vertex)
                if neighbor not in visited
            )
    return path

